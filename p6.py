'''
----Identity operators----

---> Identity iperators are also returns two conditions either true or false
---> If the condition is true returns TRUE
---> If the condition is false return FALSE

Types:
1. is
2. is not

'''
word1=str(input("Enter the word1: "))
word2=str(input("Enter the word2: "))

print(word1 is word2)
print(word1==word2)

print(word1 is not word2)